import type { ComponentMapping, PropMapping } from "../src/mapping.ts";

const cell = (value: string) => (value === "" ? "—" : value.replaceAll("|", "\\|"));
const code = (names: readonly string[]) => names.map((name) => `\`${name}\``).join(", ");

const values = (prop: PropMapping) =>
  prop.values === undefined
    ? ""
    : Object.entries(prop.values)
        .map(([from, to]) =>
          String(to) === from ? `\`${from}\`` : `\`${from}\` → \`${String(to)}\``,
        )
        .join(", ");

const fileOf = (component: string) =>
  `src/components/${component.replaceAll(/(?<!^)([A-Z])/g, "-$1").toLowerCase()}.tsx`;

function componentSection(
  mapping: ComponentMapping,
  styleProps: readonly string[],
  passthrough: boolean,
): string {
  const entries = Object.entries(mapping.props);
  const identityStyle = entries
    .filter(([name, prop]) => prop.identity === true && styleProps.includes(name))
    .map(([name]) => name);
  const rows = entries
    .filter(([name, prop]) => !(prop.identity === true && styleProps.includes(name)))
    .map(([name, prop]) =>
      prop.identity === true
        ? `| \`${name}\` | \`${name}\` | identity | passed through unchanged |`
        : `| \`${name}\` | ${cell(prop.kit)} | ${cell(values(prop))} | ${cell(prop.note ?? "")} |`,
    );
  if (identityStyle.length > 0)
    rows.push(
      `| style props (${code(identityStyle)}) | same names | identity | passed through unchanged |`,
    );
  const source = passthrough
    ? "`src/passthrough-components.ts` (generic `passthrough`)"
    : `\`${fileOf(mapping.component)}\` (export \`mapping\`)`;
  return [
    `## ${mapping.component}`,
    `Kit: ${code(mapping.kit)} · source: ${source}`,
    [
      "| Contract prop | Kit | Values (contract → kit) | Notes |",
      "|---|---|---|---|",
      ...rows,
    ].join("\n"),
  ].join("\n\n");
}

/** MAPPING.md: contract → Chakra UI v1, generated from every component's mapping (DEC-004, DEC-005). */
export function renderMappingMarkdown(
  mappings: readonly ComponentMapping[],
  passthroughNames: readonly string[],
  iconKitNames: Readonly<Record<string, string>>,
  styleProps: readonly string[],
): string {
  return (
    [
      "# ui-kit-one → Chakra UI v1 mapping",
      "> Generated by `pnpm docs` from the component mappings. Do not edit by hand.",
      [
        "Contract prop names and values equal the kit's wherever a prop is plain data (DEC-005), so most props are **identity**: passed through unchanged, kit defaults apply when omitted. Only translated props are declared by hand.",
        "",
        `- Passthrough components (one registry line each): ${code(passthroughNames)}.`,
        "- Custom components hold their implementation and mapping in one file. To remap a component, edit that file (and its facade in `src/kit/` when the kit API differs), then run `pnpm docs`.",
      ].join("\n"),
      ...mappings.map((mapping) =>
        componentSection(mapping, styleProps, passthroughNames.includes(mapping.component)),
      ),
      [
        "## Icons",
        "Source: `src/icon-map.ts` (`ICON_KIT_NAMES`); kit icons are facades in `src/kit/icons.ts`.",
        [
          "| Contract icon | Kit icon |",
          "|---|---|",
          ...Object.entries(iconKitNames).map(([name, kit]) => `| \`${name}\` | \`${kit}\` |`),
        ].join("\n"),
      ].join("\n\n"),
    ].join("\n\n") + "\n"
  );
}
