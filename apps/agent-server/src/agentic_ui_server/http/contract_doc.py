def _json(value: Any) -> str:
    return "```json\n" + json.dumps(value, ensure_ascii=False, indent=2) + "\n```"


def _fields(fields: tuple[Field, ...]) -> list[str]:
    rows = ["| field | type | required | meaning |", "|---|---|---|---|"]
    return rows + [
        f"| `{f.name}` | {f.type} | {'yes' if f.required else 'no'} | {f.meaning}"
        f"{f' ({f.constraint})' if f.constraint else ''} |"
        for f in fields
    ]


def _route(route: Route, body: Any, query: str, response: Any) -> list[str]:
    where = "query parameters" if route.method == "GET" else "JSON body"
    lines = [f"### `{route.method} {{base}}{route.path}`{' (OPTIONAL)' if route.optional else ''}", "", route.summary]
    if route.request:
        lines += ["", f"Request ({where}):", "", *_fields(route.request)]
    lines += ["", "Response (200):", "", *_fields(route.response)]
    lines += ["", "Status codes: " + ", ".join(f"`{s}`" for s in route.statuses), "", "Example:", ""]
    lines += [f"`{route.method} {{base}}{route.path}{query}`", ""]
    if body is not None:
        lines += [_json(body), ""]
    lines += [f"→ `{response.status}`", "", _json(response.body)]
    return lines


