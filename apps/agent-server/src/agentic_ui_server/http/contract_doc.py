def render() -> str:
    server, repairs = ServerSettings(), RepairSettings().max_attempts
    endpoints = ["| method | path | optional | purpose |", "|---|---|---|---|"] + [
        f"| {r.method} | `{{base}}{r.path}` | {'yes' if r.optional else 'no'} | {r.summary.split('. ')[0]} |"
        for r in ROUTES
    ]
    statuses = ["| status | meaning |", "|---|---|"] + [f"| {c} | {t} |" for c, t in STATUS_TEXT.items()]
    out = [
        _PROSE.format(
            version=__version__,
            base_path=server.base_path,
            host=server.host,
            port=server.port,
            max_body=server.max_body_bytes,
            queue=LimitSettings().max_queue_per_chat,
            endpoints="\n".join(endpoints),
            repairs=repairs,
            replies=repairs + 1,
            request_s=f"{TimeoutSettings().request_s:g}",
            surface=SURFACE_ID,
            retry=RETRY_EVENT,
            error_fields="\n".join(_fields(ERROR)),
            statuses="\n".join(statuses),
        )
    ]
    for route, body, query, response in examples():
        out += ["", *_route(route, body, query, response)]
    return "\n".join(out) + "\n"


