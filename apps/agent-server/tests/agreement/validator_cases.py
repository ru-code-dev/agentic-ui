"""Validator agreement corpus and the generated hand-over ``validator-cases`` (SV-C23).

Corpus: every example payload (valid) + every applicable mutation of every example (``mutate.py``).
``apps/agent-server/validator-cases/cases.json`` (committed, SV-C28): chats from an empty state, each a list of
steps (one reply's messages) with the expected verdict of that step (the surface referee: the renderer's own
state, ``surface-referee.mjs``) and the reference Python validator's problems: every example, per mutation its two
smallest mutants (a follow-up example or mutant after its base composition), and the multi-turn scenarios of
``sequences.py`` (create → update → action → update → delete, delete-then-create, update after delete, …).
Regenerate with
``python -m tests.agreement.validator_cases --write`` (from apps/agent-server); the agreement test fails while
the committed file differs from a fresh one.
"""

import json
import sys
from pathlib import Path
from typing import Any

from agentic_ui_server.validation import validate_payload
from agentic_ui_server.validation.refs import JSON_ONLY_KEYWORDS

from ..support.node import CATALOG_PKG, run_referee
from .mutate import MUTATIONS, mutants
from .sequences import as_chat, bases, judge_chats, scenarios

CASES_FILE = Path(__file__).resolve().parents[2] / "validator-cases" / "cases.json"
PER_MUTATION = 2


def examples() -> list[tuple[str, list]]:
    files = sorted((CATALOG_PKG / "examples").glob("*/*.json"))
    return [(f"{p.parent.name}/{p.stem}", json.loads(p.read_text(encoding="utf-8"))["messages"]) for p in files]


def corpus(extra: list[tuple[str, list]] = ()) -> list[dict[str, Any]]:
    cases = [{"id": name, "mutation": None, "messages": msgs} for name, msgs in [*examples(), *extra]]
    for name, msgs in examples():
        cases += [
            {"id": cid, "mutation": mutation, "messages": broken} for cid, mutation, broken in mutants(name, msgs)
        ]
    return cases


def judge(cases: list[dict[str, Any]]) -> tuple[dict, list[dict[str, Any]]]:
    """Node referee + Python verdicts for ``cases`` (the referee's ``refMap`` and ``jsonOnly`` in the dict)."""
    node = run_referee("validator-referee.mjs", [{"id": c["id"], "messages": c["messages"]} for c in cases])
    verdicts = {r["id"]: r for r in node["results"]}
    out = []
    for case in cases:
        errors = validate_payload(case["messages"])
        ref = verdicts[case["id"]]
        out.append({**case, "node_valid": ref["valid"], "node_error": ref["error"], "python_errors": errors})
    return {"refMap": node["refMap"], "jsonOnly": node["jsonOnly"]}, out


def chats(judged: list[dict[str, Any]]) -> list[tuple[str, str | None, list[list]]]:
    """``(id, mutation, steps)``: the chosen payloads as chats, then the multi-turn scenarios."""
    chosen = [c for c in judged if c["mutation"] is None]
    for mutation in MUTATIONS:
        of_kind = sorted((c for c in judged if c["mutation"] == mutation), key=lambda c: len(json.dumps(c["messages"])))
        chosen += of_kind[:PER_MUTATION]
    known = bases(examples())
    out = [(c["id"], c["mutation"], as_chat(c["messages"], known)) for c in chosen]
    return out + [(name, "multi-turn", steps) for name, steps in scenarios().items()]


def bundle(judged: list[dict[str, Any]]) -> dict[str, Any]:
    picked = chats(judged)
    steps = judge_chats({cid: chat for cid, _, chat in picked})
    by_chat: dict[str, list[dict]] = {}
    for step in steps:
        by_chat.setdefault(step["chat"], []).append(step)
    return {
        "$comment": "SV-C23 / SV-C28 validator cases, generated by "
        "apps/agent-server/tests/agreement/validator_cases.py."
        " Each case is one chat from an empty state: steps[] = the replies in order, each checked merged into the "
        "surfaces of the earlier VALID steps (an invalid step leaves the state as it was). expected.valid = the "
        "renderer state's verdict (@a2ui/agent RendererState over web_core + the project rules); nodeError = its "
        "error; pythonErrors = every problem the reference Python validator reports. A conforming validator gives "
        "the same verdict for every step. jsonOnlyKeywords: per function, args field ('' = the args object) -> JSON "
        "Schema keywords the renderer does not check (drop them, handover/README.md step 2).",
        "jsonOnlyKeywords": {
            name: {k: list(v) for k, v in fields.items()} for name, fields in JSON_ONLY_KEYWORDS.items()
        },
        "cases": [
            {
                "id": cid,
                "mutation": mutation,
                "steps": [
                    {
                        "messages": step["messages"],
                        "expected": {
                            "valid": step["node"]["valid"],
                            "nodeError": step["node"]["error"],
                            "pythonErrors": step["python_errors"],
                        },
                    }
                    for step in by_chat[cid]
                ],
            }
            for cid, mutation, _ in picked
        ],
    }


def invalid_examples(judged: list[dict[str, Any]]) -> list[str]:
    """A3-25: ids of unmutated examples that Node or Python rejects (the bundle must not ship them as valid)."""
    return [c["id"] for c in judged if c["mutation"] is None and (not c["node_valid"] or c["python_errors"])]


def bundle_text(judged: list[dict[str, Any]]) -> str:
    return json.dumps(bundle(judged), ensure_ascii=False, indent=1) + "\n"


def write(judged: list[dict[str, Any]], target: Path = CASES_FILE) -> None:
    """Write the bundle; stop (exit 1, naming them) when an unmutated example is invalid (A3-25)."""
    broken = invalid_examples(judged)
    if broken:
        sys.exit(f"validator_cases: {len(broken)} example(s) invalid against the contract, not written: {broken}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(bundle_text(judged), encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    if "--print" in sys.argv:  # check:generated (A3-29)
        judged_cases = judge(corpus())[1]
        if invalid_examples(judged_cases):
            sys.exit(f"validator_cases: invalid example(s): {invalid_examples(judged_cases)}")
        sys.stdout.write(bundle_text(judged_cases))
    elif "--write" in sys.argv:
        write(judge(corpus())[1])
    else:
        sys.exit("usage: python -m tests.agreement.validator_cases --write | --print")
