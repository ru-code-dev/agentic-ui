/**
 * DEC-032: joins the ID list with the test tags and renders docs/TRACEABILITY.md.
 *
 * Status of an in-scope ID: `pending: <phase>` while its phase is open (tests found so far are
 * listed), else `proven` with ≥1 tagged test or pipeline check (an umbrella ID with `covers`: when
 * every in-scope covered ID is proven), else a problem (missing proof).
 * Out-of-scope IDs show the DEC that removed them.
 */

import { splitIds } from "./tags.mjs";

const DEC = /\bDEC-\d{3}\b/g;

/** Status of one in-scope ID of a done phase; `covered` = statuses of its `covers` IDs. */
function doneStatus(entry, proofCount, covered, problems) {
  if (covered) {
    const unproven = covered.filter(([, status]) => status !== "proven").map(([id]) => id);
    if (unproven.length === 0) return "proven";
    problems.push(
      `${entry.id}: phase ${entry.phase} is done but covered IDs are not proven: ${unproven.join(", ")}`,
    );
    return "MISSING PROOF";
  }
  if (proofCount > 0) return "proven";
  problems.push(`${entry.id}: phase ${entry.phase} is done but no test or check proves it`);
  return "MISSING PROOF";
}

/** `{ rows, problems }` for validated ids (`loadIds`) and collected tags (`collectTags`). */
export function buildMatrix({ phases, ids }, tags) {
  const proofs = new Map(ids.map((entry) => [entry.id, new Set()]));
  const problems = [];
  for (const tag of tags) {
    if (proofs.has(tag.id)) proofs.get(tag.id).add(tag.test);
    else problems.push(`${tag.at}: tag names unknown ID ${tag.id}`);
  }
  const byId = new Map(ids.map((entry) => [entry.id, entry]));
  const statuses = new Map();
  const statusOf = (entry) => {
    if (statuses.has(entry.id)) return statuses.get(entry.id);
    statuses.set(entry.id, "MISSING PROOF"); // a covers cycle resolves to unproven
    let status;
    if (entry.scope === "out") {
      status = `out of scope (${(String(entry.evidence).match(DEC) ?? []).join(", ")})`;
    } else if (phases[entry.phase] === "open") {
      status = entry.gap
        ? `pending: ${entry.phase} (gap: ${entry.gap})`
        : `pending: ${entry.phase}`;
    } else {
      const covered = entry.covers
        ? splitIds(entry.covers.join(","))
            .filter((id) => byId.has(id) || !problems.push(`${entry.id}: covers unknown ID ${id}`))
            .filter((id) => byId.get(id).scope === "in")
            .map((id) => [id, statusOf(byId.get(id))])
        : null;
      status = doneStatus(
        entry,
        proofs.get(entry.id).size + (entry.checks ?? []).length,
        covered,
        problems,
      );
    }
    statuses.set(entry.id, status);
    return status;
  };
  const rows = ids.map((entry) => ({
    ...entry,
    tests: [...(proofs.get(entry.id) ?? [])].toSorted(),
    checks: entry.checks ?? [],
    status: statusOf(entry),
  }));
  return { rows, problems };
}

const cell = (text) =>
  String(text).replaceAll("|", "\\|").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

function phaseTable(phases, rows) {
  const lines = ["| phase | state | in-scope IDs | proven | pending |", "|---|---|---|---|---|"];
  for (const [phase, state] of Object.entries(phases)) {
    const own = rows.filter((row) => row.scope === "in" && row.phase === phase);
    const count = (prefix) => own.filter((row) => row.status.startsWith(prefix)).length;
    lines.push(
      `| ${phase} | ${state} | ${own.length} | ${count("proven")} | ${count("pending")} |`,
    );
  }
  return lines;
}

function proofCell(row) {
  const items = [
    ...(row.covers ? [`covers: ${row.covers.join(", ")}`] : []),
    ...row.tests,
    ...row.checks.map((check) => `check: pnpm ${check}`),
  ];
  return items.length === 0 ? "—" : items.map(cell).join("<br>");
}

function scopeCell(row) {
  return row.scope === "out"
    ? `out: ${cell(row.reason)} (${cell(row.evidence)})`
    : `in (${row.phase})`;
}

/** The generated markdown (byte-stable for the same input). */
export function renderMatrix({ phases }, rows) {
  const total = (prefix) => rows.filter((row) => row.status.startsWith(prefix)).length;
  return [
    "# Traceability matrix",
    "",
    "<!-- Generated by `pnpm trace` (node scripts/traceability.mjs --write) from docs/TRACEABILITY.ids.json and test tags (DEC-032). Do not edit. -->",
    "",
    "Every requirement ID → proving tests or checks → status. A test proves an ID with a tag `[ID]` in its title (Python: in the test docstring or in apps/agent-server/tests/traceability.json). `pnpm check:trace` fails on an in-scope ID of a done phase without proof, a tag naming an unknown ID, or a stale file.",
    "",
    `- IDs: ${rows.length}, proven: ${total("proven")}, pending: ${total("pending")}, out of scope: ${total("out")}`,
    "",
    "## Phases",
    "",
    ...phaseTable(phases, rows),
    "",
    "## Matrix",
    "",
    "| ID | source | scope | title | proving tests | status |",
    "|---|---|---|---|---|---|",
    ...rows.map(
      (row) =>
        `| ${row.id} | ${row.source} | ${scopeCell(row)} | ${cell(row.title)} | ${proofCell(row)} | ${row.status} |`,
    ),
    "",
  ].join("\n");
}
